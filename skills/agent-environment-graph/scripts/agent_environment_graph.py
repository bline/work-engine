def _referenced_entity_ids(role: dict[str, Any], environment: dict[str, Any]) -> set[str]:
    entity_ids = {
        identifier
        for group in environment["entities"].values()
        for identifier in group
    }
    referenced = {
        target
        for field in RELATION_LISTS
        if field != "bound_by"
        for target in role.get(field, [])
    }
    referenced.update(role.get("observation_limits", {}))
    referenced.update(item["target"] for item in role.get("may_mutate", []))
    referenced.update(
        item["mediated_by"]
        for item in role.get("mediated_transitions", [])
        if item["mediated_by"] in entity_ids
    )
    return referenced


def _direct_invariant_ids(role: dict[str, Any]) -> list[str]:
    identifiers = set(role.get("bound_by", []))
    identifiers.update(
        invariant_id
        for invariant_ids in role.get("must_require", {}).values()
        for invariant_id in invariant_ids
    )
    return sorted(identifiers)


def _referenced_invariant_ids(role: dict[str, Any], catalog: dict[str, Any]) -> list[str]:
    identifiers = set(_direct_invariant_ids(role))
    pending = list(identifiers)
    while pending:
        identifier = pending.pop()
        for related in catalog["invariants"][identifier]["relations"]:
            if related not in identifiers:
                identifiers.add(related)
                pending.append(related)
    return sorted(identifiers)


def render_role_yaml(
    catalog: dict[str, Any], environment: dict[str, Any], role_id: str,
    invariant_path: Path, environment_path: Path,
) -> str:
    """Render a lossless role-scoped analysis projection from both canonical inputs."""
    role = environment["roles"][role_id]
    referenced_entities = _referenced_entity_ids(role, environment)
    entities = {
        kind: {
            identifier: item
            for identifier, item in mapping.items()
            if identifier in referenced_entities
        }
        for kind, mapping in environment["entities"].items()
    }
    direct_invariant_ids = _direct_invariant_ids(role)
    invariant_ids = _referenced_invariant_ids(role, catalog)
    invariants = {
        identifier: catalog["invariants"][identifier]
        for identifier in invariant_ids
    }
    mechanism_ids = {
        mechanism
        for invariant in invariants.values()
        for mechanism in invariant["mechanisms"]
    }
    mechanism_ids.update(
        item["mechanism"]
        for mapping in entities.values()
        for item in mapping.values()
        if "mechanism" in item
    )
    referenced_role_ids = set(role.get("must_require", {}))
    referenced_role_ids.update(
        item["mediated_by"]
        for item in role.get("mediated_transitions", [])
        if item["mediated_by"] in environment["roles"]
    )
    projection = {
        "schema_version": 1,
        "document_id": f"{environment['document_id']}.{role_id}.projection",
        "status": "generated_projection",
        "generated_by": "skills/agent-environment-graph/scripts/agent_environment_graph.py",
        "source_inputs": _source_hashes(invariant_path, environment_path),
        "environment_context": {
            field: environment[field]
            for field in ("document_id", "status", "verified_on", "scope", "sources", "semantics", "analysis_queries")
            if field in environment
        },
        "role_id": role_id,
        "role": role,
        "direct_invariant_ids": direct_invariant_ids,
        "referenced_roles": {
            identifier: {
                field: environment["roles"][identifier][field]
                for field in ("label", "objective", "context_lifetime")
            }
            for identifier in sorted(referenced_role_ids)
        },
        "entities": entities,
        "invariants": invariants,
        "mechanisms": {
            identifier: catalog["mechanisms"][identifier]
            for identifier in sorted(mechanism_ids)
        },
    }
    return GENERATED_YAML_COMMENT + "\n" + yaml.safe_dump(
        projection, sort_keys=False, allow_unicode=True, width=100,
    )


def render_site(
    catalog: dict[str, Any], environment: dict[str, Any],
    invariant_path: Path, environment_path: Path,
) -> tuple[str, dict[str, str]]:
    pages = {"README.md": render_role_index(catalog, environment, invariant_path, environment_path)}
    for role_id, role in environment["roles"].items():
        slug = _role_slug(role)
        markdown_filename = slug + ".md"
        yaml_filename = slug + ".yaml"
        require(markdown_filename not in pages and yaml_filename not in pages, f"duplicate role page slug: {slug}")
        pages[markdown_filename] = render_role_page(catalog, environment, role_id, invariant_path, environment_path)
        pages[yaml_filename] = render_role_yaml(catalog, environment, role_id, invariant_path, environment_path)
    return render_overview(catalog, environment, invariant_path, environment_path), pages


def _is_generated_artifact(path: Path) -> bool:
    try:
        source = path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        return False
    return GENERATED_COMMENT in source or GENERATED_YAML_COMMENT in source


def write_site(output: Path, role_output_dir: Path, overview: str, pages: dict[str, str]) -> list[str]:
    output.parent.mkdir(parents=True, exist_ok=True)
    role_output_dir.mkdir(parents=True, exist_ok=True)
    output.write_text(overview, encoding="utf-8")
    for filename, content in pages.items():
        (role_output_dir / filename).write_text(content, encoding="utf-8")
    removed: list[str] = []
    for candidate in sorted(role_output_dir.iterdir()):
        if candidate.suffix not in {".md", ".yaml"}:
            continue
        if candidate.name in pages:
            continue
        if _is_generated_artifact(candidate):
            candidate.unlink()
            removed.append(str(candidate))
    return removed


def check_site(output: Path, role_output_dir: Path, overview: str, pages: dict[str, str]) -> None:
    require(output.read_text(encoding="utf-8") == overview, f"rendered view is stale: {output}")
    require(role_output_dir.is_dir(), f"missing role output directory: {role_output_dir}")
    for filename, content in pages.items():
        path = role_output_dir / filename
        require(path.is_file(), f"missing generated role page: {path}")
        require(path.read_text(encoding="utf-8") == content, f"generated role page is stale: {path}")
    expected = set(pages)
    unexpected = sorted(
        path.name
        for path in role_output_dir.iterdir()
        if path.suffix in {".md", ".yaml"}
        and path.name not in expected
        and _is_generated_artifact(path)
    )
    require(not unexpected, f"unexpected generated role artifacts: {', '.join(unexpected)}")


def validate_judgments(path: Path) -> dict[str, Any]:
    data = json.loads(path.read_text(encoding="utf-8"))
    require(isinstance(data, dict) and set(data) == {"schema_version", "producer", "judgments"}, "judgment artifact has invalid fields")
    require(data["schema_version"] == 1, "judgment schema_version must be 1")
    require(isinstance(data["producer"], str) and data["producer"].strip(), "judgment producer is required")
    judgments = data["judgments"]
    require(isinstance(judgments, list), "judgments must be a list")
    ids = set()
    required = {"id", "category", "subject", "conclusion", "evidence", "changes_contract", "human_approval"}
    for index, item in enumerate(judgments):
        require(isinstance(item, dict) and set(item) == required, f"judgments[{index}] has invalid fields")
        require(isinstance(item["id"], str) and item["id"] not in ids, f"judgments[{index}].id is missing or duplicate")
        ids.add(item["id"])
        require(item["category"] in SEMANTIC_CATEGORIES, f"judgments[{index}].category is unsupported")
        for field in ("subject", "conclusion"):
            require(isinstance(item[field], str) and item[field].strip(), f"judgments[{index}].{field} is required")
        _unique_strings(item["evidence"], f"judgments[{index}].evidence")
        require(bool(item["evidence"]), f"judgments[{index}].evidence must not be empty")
        require(isinstance(item["changes_contract"], bool), f"judgments[{index}].changes_contract must be boolean")
        if item["changes_contract"]:
            approval = item["human_approval"]
            require(isinstance(approval, dict) and set(approval) == {"approver", "reference"}, f"judgments[{index}] contract change requires human approval")
            require(all(isinstance(value, str) and value.strip() for value in approval.values()), f"judgments[{index}] approval is incomplete")
        else:
            require(item["human_approval"] is None, f"judgments[{index}] non-contract judgment must not claim approval")
    return {"status": "valid", "judgments": len(judgments)}


def parser() -> argparse.ArgumentParser:
    result = argparse.ArgumentParser()
    sub = result.add_subparsers(dest="command", required=True)
    for name in ("validate", "candidates", "analyze", "render", "check"):
        command = sub.add_parser(name)
        command.add_argument("--invariants", type=Path, required=True)
        command.add_argument("--environments", type=Path, required=True)
        if name == "render":
            command.add_argument("--output", type=Path, required=True)
            command.add_argument("--role-output-dir", type=Path, required=True)
        if name == "check":
            command.add_argument("--rendered", type=Path, required=True)
            command.add_argument("--role-output-dir", type=Path, required=True)
    judgments = sub.add_parser("validate-judgments")
    judgments.add_argument("path", type=Path)
    return result


def main() -> int:
    arguments = parser().parse_args()
    try:
        if arguments.command == "validate-judgments":
            result = validate_judgments(arguments.path)
        else:
            catalog, environment = load_model(arguments.invariants, arguments.environments)
            if arguments.command == "validate": result = {"status": "valid", **analyze(catalog, environment)["counts"]}
            elif arguments.command == "candidates": result = candidates(catalog, environment)
            elif arguments.command == "analyze": result = analyze(catalog, environment)
            else:
                overview, pages = render_site(catalog, environment, arguments.invariants, arguments.environments)
                if arguments.command == "render":
                    removed = write_site(arguments.output, arguments.role_output_dir, overview, pages)
                    result = {
                        "status": "rendered", "output": str(arguments.output),
                        "role_output_dir": str(arguments.role_output_dir),
                        "role_pages": sorted(pages), "removed_stale_pages": removed,
                    }
                else:
                    check_site(arguments.rendered, arguments.role_output_dir, overview, pages)
                    result = {
                        "status": "current", "rendered": str(arguments.rendered),
                        "role_output_dir": str(arguments.role_output_dir),
                        "role_pages": sorted(pages),
                    }
        print(json.dumps(result, indent=2, sort_keys=True))
        return 0
    except (GraphError, OSError, json.JSONDecodeError) as error:
        print(json.dumps({"status": "invalid", "error": str(error)}, sort_keys=True), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
