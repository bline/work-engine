    lines = [
        "# Agent Environment Graphs", "",
        GENERATED_COMMENT,
        f"<!-- invariant-sha256: {inv_digest} -->", f"<!-- environment-sha256: {env_digest} -->", "",
        "This is a deterministic view of [`agent-environments.yaml`](agent-environments.yaml).",
        "Invariant and machinery truth remains owned by [`workflow-invariants.md`](workflow-invariants.md);",
        "role projection truth remains owned by the YAML input. Edit those owners and regenerate this view.", "",
        "Analysis produced by the CLI is candidate evidence only. Semantic classification and genuine contract changes",
        "remain AI-judged and human-authorized respectively.", "",
        "The diagrams use one visible entry edge per relation group to avoid unreadable fan-out; the relation tables",
        "below them enumerate every individual edge. Invariant node text is a shortened view of the catalog condition.", "",
        "Color uses the same basic GitHub circle families in diagrams and tables. Text remains beside every marker",
        "so semantic meaning does not depend on color alone.", "",
    ]
    lines += _legend_lines()
    entity_labels, invariant_labels, invariant_styles, display_labels = _display_context(catalog, environment)
    for role_id, role in environment["roles"].items():
        lines += [f"## {role['label']}", ""]
        lines += _role_graph_lines(
            role_id, role, entity_labels, invariant_labels, invariant_styles,
        )
