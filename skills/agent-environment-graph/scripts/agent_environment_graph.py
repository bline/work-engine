def _detail_rows(role: dict[str, Any], entity_labels: dict[str, str]) -> list[str]:
    lines: list[str] = []
    observation_limits = role.get("observation_limits", {})
    if observation_limits:
        lines += ["## Observation limits", "", "| Target | Visible projection |", "| --- | --- |"]
        lines += [
            f"| `{target}` ({_markdown_cell(entity_labels.get(target, target))}) | {_markdown_cell(limit)} |"
            for target, limit in observation_limits.items()
        ] + [""]
    mutations = role.get("may_mutate", [])
    if mutations:
        lines += ["## Mutation boundaries", "", "| Target | Authorized boundary |", "| --- | --- |"]
        lines += [
            f"| `{item['target']}` ({_markdown_cell(entity_labels[item['target']])}) | "
            f"{_markdown_cell(item['boundary'])} |"
            for item in mutations
        ] + [""]
    transitions = role.get("mediated_transitions", [])
    if transitions:
        lines += ["## Mediated transitions", "", "| Transition | Mediated by |", "| --- | --- |"]
        lines += [
            f"| {_markdown_cell(item['transition'])} | `{item['mediated_by']}` |"
            for item in transitions
        ] + [""]
    independence = role.get("independence", {})
    if independence:
        lines += ["## Independence boundary", "", "| Constraint | Value |", "| --- | --- |"]
        for field, value in independence.items():
            values = value if isinstance(value, list) else [value]
            rendered = "<br/>".join(_markdown_cell(str(item)) for item in values)
            lines.append(f"| `{field}` | {rendered} |")
        lines.append("")
    denials = role.get("forbidden_from", [])
    if denials:
        lines += ["## Explicit non-authority", ""]
        lines += [f"- {_markdown_cell(item)}" for item in denials] + [""]
    return lines


