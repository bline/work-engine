"""Write corpus/REVISION-3.md (change matrix, audit of revision 2's changes, added cases) and corpus/INVARIANT-COVERAGE.md
(per invariant: a positive case, a violating case, and their expected financial, attribution and admission states).
Usage: rev3_summary.py <corpus_dir>"""
import collections, glob, json, os, sys

corpus = sys.argv[1]
cs = {json.load(open(p))['case_id']: json.load(open(p)) for p in sorted(glob.glob(os.path.join(corpus, 'cases', '*.json')))}
RANK = {'admitted': 0, 'refused': 1, 'not_established': 2}
STRUCTURAL = ('R-07 6.2', 'R-10 10:', 'R-04 12.3 A-5')       # field additions applied to every case (execution, billing, reopened, commitment kind)


def first_dec(c): return (c['evaluations'][0]['expected'].get('admission') or {}).get('decision')


def ub(a):
    v, s = a['valuation'], a['settlement']
    return v.get('state') == 'valued' and v.get('complete') and (s['decision'] == 'not_applicable' or (s['decision'] == 'valid' and s.get('basis') == 'usage'))


L = ['# Corpus revision 3 (contract `1.2-s1`, P1.30)', '',
     'Generated by `tools/rev3_summary.py`. Revisions 1 and 2 are preserved unchanged (P1.28 and P1.29). Every changed field of a '
     'revision-2 case is in its `revisions_r3` log, and `validate_corpus.py revisions` proves that undoing that log restores the '
     'revision-2 case exactly. Historical blocks are unchanged (121/121 reproduced byte-identically by a gated A1.3.4 rerun).', '']
old = [c for c in cs.values() if not c.get('added_in') == '1.2-s1']; new = [c for c in cs.values() if c.get('added_in') == '1.2-s1']
norm = [c for c in old if any(not r['rule'].startswith(STRUCTURAL) for r in c['revisions_r3'])]
L += [f'**Totals.** {len(cs)} cases: {len(old)} from revision 2, {len(new)} added. Every revision-2 case gains the fields `execution`, `billing`, '
      f'`reopened` and commitment `kind` (structural). {len(norm)} revision-2 cases have a change beyond those structural fields.', '',
      '| Rule | Field changes | Cases |', '|---|---|---|']
rc, rcases = collections.Counter(), collections.defaultdict(set)
for c in old:
    for r in c['revisions_r3']:
        k = r['rule'].split(':')[0]; rc[k] += 1; rcases[k].add(c['case_id'])
L += [f'| {k} | {n} | {len(rcases[k])} |' for k, n in sorted(rc.items())]
L += ['', '## Change matrix: revision-2 cases with a non-structural change', '',
      '| Case | Role | Rules (non-structural) | Admission rev 2 → rev 3 | Direction | A1.3.4 |', '|---|---|---|---|---|---|']
for c in norm:
    rules = sorted({r['rule'].split(':')[0] for r in c['revisions_r3'] if not r['rule'].startswith(STRUCTURAL)})
    dec = [r for r in c['revisions_r3'] if r['field'].endswith('admission.decision')]
    adm = '; '.join(f'{r["field"].split("/")[0]}: {r["from"]} → {r["to"]}' for r in dec) or 'unchanged'
    dirn = '; '.join('more permissive' if RANK[r['to']] < RANK[r['from']] else 'less permissive' for r in dec) or '—'
    L.append(f'| `{c["case_id"]}` | {c["role"]} | {", ".join(rules)} | {adm} | {dirn} | {(c["historical"].get("a134_086bdec1") or {}).get("decision")} |')
L += ['', '**Direction of admission changes:** "less permissive" means the decision moved towards `not_established` or `refused` under the '
      'rank admitted < refused < not_established. The single move from `not_established` to `refused` (`D1-closed-objective-provisional`, '
      'Q11) does not change whether admission is denied; it records that closure, not accounting, decides it.', '']
# audit of revision 2's 58 changes
r2 = [c for c in old if c.get('revisions')]
fb2 = [(c['case_id'], r['field'].split('[', 1)[1].split(']')[0]) for c in r2 for r in c['revisions'] if r['rule'].startswith('FB-2')]
with_bound = [(cid, k) for cid, k in fb2 if ub(next(a for a in cs[cid]['expected']['attempts'] if a['key'] == k))]
o6 = sorted({c['case_id'] for c in r2 for r in c['revisions'] if r['rule'].startswith('O-6')})
dec2 = [(c['case_id'], r) for c in r2 for r in c['revisions'] if r['field'].endswith('admission.decision')]
L += ['## Audit of revision 2\'s 58 changed cases (owner question: correct uncertainty or overbroad blocking?)', '',
      f'- **FB-2 flips:** {len(fb2)} attempt highs moved from `Exact` to `AtLeast` in {len({x[0] for x in fb2})} cases. Attempts among them with a usage '
      f'bound (complete usage over established sets): **{len(with_bound)}** {with_bound}. Every flip therefore rests on a reservation or proxy charge alone, '
      'which the owner\'s Q2 and Q10 dispositions require to be unresolved. None of them blocked an attempt that had a usage bound.',
      f'- **O-6 renames:** {len(o6)} cases changed `uncertain`/`NoAdmission` to `unadmitted` and `OwnershipUncertain` to `HistoricalUnadmitted`. '
      'No admission decision changed through O-6 alone.',
      f'- **Admission decisions changed in revision 2:** {len(dec2)}. Their revision-3 values:', '']
L += ['| Case | Revision 1 | Revision 2 | Revision 3 | Why |', '|---|---|---|---|---|']
for cid, r in dec2:
    ev = r['field'].split('/')[0]; now = next(e for e in cs[cid]['evaluations'] if e['name'] == ev)['expected']['admission']['decision']
    why = 'Q11 closure precedence' if now == 'refused' and r['to'] == 'not_established' else 'reservation-only exposure (FB-2, D5)'
    L.append(f'| `{cid}` ({ev}) | {r["from"]} | {r["to"]} | {now} | {why} |')
L += ['', '**Assessment.** Revision 2\'s changes follow from the owner\'s rules and are not overbroad in the sense of blocking execution '
      'that has a usage bound. The cost is operational: every objective that holds a reservation-only attempt, an open commitment (revision 3) '
      'or an unresolved predecessor attempt is not established until the billing resolves. Admitted valid controls: revision 1 counted 27 in its '
      'A1 text; revision 2 had 17; revision 3 has 17 (14 surviving plus 3 new genuinely safe controls), against an unchanged minimum of 15.', '']
L += ['## Added cases', '', '| Case | Role | Finding | Admission | A1.3.4 |', '|---|---|---|---|---|']
for c in new:
    L.append(f'| `{c["case_id"]}` | {c["role"]} | {", ".join(c["findings"]) or c["group"]} | {"; ".join(e["name"] + ": " + e["expected"]["admission"]["decision"] for e in c["evaluations"])} | {(c["historical"].get("a134_086bdec1") or {}).get("decision")} |')
va = [c['case_id'] for c in cs.values() if c['role'] in ('valid_control', 'control') and first_dec(c) == 'admitted' and not any(a['blocking'] for a in c['expected']['attempts'])]
L += ['', f'## Admitted valid controls ({len(va)}; minimum 15, unchanged)', '', ', '.join(f'`{x}`' for x in va), '']
open(os.path.join(corpus, 'REVISION-3.md'), 'w').write('\n'.join(L) + '\n')

# invariant coverage: positive and violating case per invariant with expected states
def state(c):
    e = c['evaluations'][0]; ee = e['expected']
    atts = c['expected']['attempts']
    fin = '; '.join(f'{a["exposure"]["high"]["kind"]}({a["exposure"]["high"]["nano"]})' if a['exposure'].get('pool') == 'pi_api' else 'codex' for a in atts) or 'no attempt'
    att = '; '.join(f'{x["ownership"]}/{x["placement"]}' for x in ee['attribution']) or 'none'
    return fin, att, (ee.get('admission') or {}).get('decision')
INV = sorted({i for c in cs.values() for i in c['invariants']}, key=lambda x: (x[4], int(x[5:])))
M = ['# Invariant coverage (contract `1.2-s1`)', '', 'Generated by `tools/rev3_summary.py`. For each invariant: a positive case (a control, expected '
     'to satisfy it with an accepting or correctly bounded result) and a violating case (a finding whose naive treatment violates it), with each '
     'case\'s expected financial state (attempt highs), attribution state and admission decision (first evaluation).', '',
     '| Invariant | Positive case | financial / attribution / admission | Violating case | financial / attribution / admission |', '|---|---|---|---|---|']
missing = []
for inv in INV:
    pos = [c for c in cs.values() if inv in c['invariants'] and c['role'] in ('valid_control', 'control')]
    neg = [c for c in cs.values() if inv in c['invariants'] and c['role'] == 'finding']
    if not pos:   # a finding's own control serves as its positive case
        pos = [cs[ctl] for c in neg for ctl in c['controls'] if ctl in cs][:1]
    p, n = (pos[0] if pos else None), (neg[0] if neg else None)
    alt = {'INV-A1': 'result-set defect: self-test `always_reject` (and `more_restrictive_than_expected`)',
           'INV-F8': 'corpus sabotage `twin differs` on the ORD pair',
           'INV-F10': 'harness requirement: two runs compared byte for byte (S2); no corpus case can violate it',
           'INV-T5': '`N03-identity-refusal-in-subscription` (lane contradicted, so the attempt is PiApi and blocks: the boundary of T5)'}
    if not p or (not n and inv not in alt): missing.append(inv)
    fmt = lambda c: ' / '.join(str(x) for x in state(c)) if c else '—'
    M.append(f'| {inv} | {"`" + p["case_id"] + "`" if p else "—"} | {fmt(p)} | {"`" + n["case_id"] + "`" if n else alt.get(inv, "—")} | {fmt(n) if n else "—"} |')
M += ['', '"Positive" means the case satisfies the invariant, which can be a correctly blocked result (for example A5, F11).',
      f'Invariants without a positive case, or without a violating case or stated violation route: {missing or "none"}.']
open(os.path.join(corpus, 'INVARIANT-COVERAGE.md'), 'w').write('\n'.join(M) + '\n')
print(f'{len(norm)} non-structural rev-2 changes, {len(new)} added, {len(va)} admitted controls; FB-2 flips {len(fb2)}, with usage bound {len(with_bound)}; invariants missing a pair: {missing}')
