"""Write corpus/REVISION-5.md (changed normative expectations with source evidence, rule, old and new outcome; added cases
with controls; profile counts) and corpus/INVARIANT-COVERAGE.md. Usage: rev5_summary.py <corpus_dir>"""
import collections, glob, json, os, sys

corpus = sys.argv[1]
cs = {json.load(open(p))['case_id']: json.load(open(p)) for p in sorted(glob.glob(os.path.join(corpus, 'cases', '*.json')))}
def fd(c): return (c['evaluations'][0]['expected'].get('admission') or {}).get('decision')
def va(c): return c['role'] in ('valid_control', 'control') and fd(c) == 'admitted' and not any(a['blocking'] for a in c['expected']['attempts'])
STRUCT = ('A-01 2.1', 'R-07 6.2')
L = ['# Corpus revision 5 (contract `1.4-s1`, P1.33)', '', 'Generated by `tools/rev5_summary.py`. Revisions 1 to 4 are preserved unchanged. Every changed field of a '
     'revision-4 case is logged in `revisions_r5` (rule, from, to), and `validate_corpus.py revisions` reconstructs revision 4 exactly. '
     'Historical blocks: 157/157 unchanged; 139/139 current-producer cases reproduce byte-identically under a gated A1.3.4 rerun.', '',
     '## Profiles', '', '| Profile | Cases | Admitted / refused / not established | Admitted valid controls | Metered |', '|---|---|---|---|---|']
for prof in ('current_producer', 'future_qualified_gate'):
    sub = [c for c in cs.values() if c['profile'] == prof]
    d = collections.Counter(e['expected']['admission']['decision'] for c in sub for e in c['evaluations'] if e['expected'].get('admission'))
    v = [c for c in sub if va(c)]; m = [c for c in v if any(a['exposure'].get('pool') == 'pi_api' for a in c['expected']['attempts'])]
    L.append(f'| {prof} | {len(sub)} | {d["admitted"]} / {d["refused"]} / {d["not_established"]} | {len(v)} | {len(m)} |')
structural = sum(1 for c in cs.values() for r in c.get('revisions_r5', []) if r['rule'].startswith(STRUCT))
L += ['', f'**Structural field additions:** {structural} (`replacement` on every attempt; `billing` re-stated). They change no amount.', '',
      '## Changed normative expectations (non-structural)', '', '| Case | Field | Old → new | Rule | Source evidence |', '|---|---|---|---|---|']
for c in cs.values():
    for r in c.get('revisions_r5', []):
        if r['rule'].startswith(STRUCT): continue
        ev = ''
        if r['field'].startswith('attempts['):
            key = r['field'][len('attempts['):].split(']')[0]; a = next(x for x in c['expected']['attempts'] if x['key'] == key); ev = ', '.join(a['evidence'])
        short = lambda x: json.dumps(x, sort_keys=True)[:70]
        L.append(f'| `{c["case_id"]}` | `{r["field"][:70]}` | {short(r["from"])} → {short(r["to"])} | {r["rule"][:110]} | {ev} |')
new = [c for c in cs.values() if c.get('added_in') == '1.4-s1']
L += ['', f'## Added cases ({len(new)}), each with its single-condition control', '', '| Case | Profile | Role | Control(s) | Decision; replacement; exposure high | Reachability |', '|---|---|---|---|---|---|']
for c in new:
    a = c['expected']['attempts'][0]
    L.append(f'| `{c["case_id"]}` | {c["profile"]} | {c["role"]} | {", ".join("`" + x + "`" for x in c["controls"]) or "—"} | {a["settlement"]["decision"]}; {a["replacement"]["reason"]}; '
             f'{a["exposure"]["high"]["kind"]}({a["exposure"]["high"]["nano"]}); admission {fd(c)} | {c["reachability"]} |')
open(os.path.join(corpus, 'REVISION-5.md'), 'w').write('\n'.join(L) + '\n')

def state(c):
    e = c['evaluations'][0]; ee = e['expected']
    fin = '; '.join(f'{a["exposure"]["high"]["kind"]}({a["exposure"]["high"]["nano"]})' if a['exposure'].get('pool') == 'pi_api' else 'codex' for a in c['expected']['attempts']) or 'no attempt'
    att = '; '.join(f'{x["ownership"]}/{x["placement"]}' for x in ee['attribution']) or 'none'
    return f'{fin} / {att} / {(ee.get("admission") or {}).get("decision")}'
INV = sorted({i for c in cs.values() for i in c['invariants']}, key=lambda x: (x[4], int(x[5:])))
ALT = {'INV-A1': 'self-test `always_reject` (fails in both profiles)', 'INV-F8': 'sabotage `twin differs`', 'INV-F10': 'harness: two runs byte for byte',
       'INV-T5': '`N03-identity-refusal-in-subscription` (lane contradicted)'}
M = ['# Invariant coverage (contract `1.4-s1`)', '', 'Generated by `tools/rev5_summary.py`. Per invariant: a positive case and a violating case with expected '
     'attempt highs / attribution / admission (first evaluation) and profile.', '', '| Invariant | Positive (profile) | state | Violating (profile) | state |', '|---|---|---|---|---|']
missing = []
for inv in INV:
    pos = [c for c in cs.values() if inv in c['invariants'] and c['role'] in ('valid_control', 'control')]
    neg = [c for c in cs.values() if inv in c['invariants'] and c['role'] == 'finding']
    if not pos: pos = [cs[x] for c in neg for x in c['controls'] if x in cs][:1]
    p = pos[0] if pos else None; n = neg[0] if neg else None
    if not p or (not n and inv not in ALT): missing.append(inv)
    M.append(f'| {inv} | {("`" + p["case_id"] + "` (" + p["profile"] + ")") if p else "—"} | {state(p) if p else "—"} | '
             f'{("`" + n["case_id"] + "` (" + n["profile"] + ")") if n else ALT.get(inv, "—")} | {state(n) if n else "—"} |')
M += ['', f'Invariants without a positive case, or without a violating case or stated route: {missing or "none"}.']
open(os.path.join(corpus, 'INVARIANT-COVERAGE.md'), 'w').write('\n'.join(M) + '\n')
print(f'{len(new)} added; structural {structural}; invariants missing a pair: {missing}')
